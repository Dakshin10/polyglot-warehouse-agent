"""50-query benchmark harness for Polyglot Warehouse Agent (PWA) NL→SQL pipeline.

Usage:
    python -m pwa.eval.benchmark [--limit N] [--fail-under PCT] [--output PATH]
    pwa benchmark [--limit N] [--fail-under PCT]
"""

import argparse
import datetime
import json
import logging
import pathlib
import sys
import time
from typing import Any, Dict, List, Tuple

from pwa.agent.pipeline.exec_agent import ast_validate_sql
from pwa.agent.pipeline.orchestrator import PipelineResult, run_query_verbose

logger = logging.getLogger("pwa.eval.benchmark")

_BENCHMARK_PATH = pathlib.Path(__file__).parent / "benchmark_queries.json"
_RESULTS_DIR = pathlib.Path(__file__).parent / "results"


def load_benchmark_queries(path: pathlib.Path = _BENCHMARK_PATH) -> List[Dict[str, Any]]:
    """Load 50 benchmark queries from JSON file."""
    if not path.exists():
        # Fall back to root relative path if needed
        path = pathlib.Path("pwa/eval/benchmark_queries.json")
    return json.loads(path.read_text(encoding="utf-8"))


def evaluate_query_conditions(
    entry: Dict[str, Any],
    result: str | PipelineResult,
) -> Tuple[bool, str, str]:
    """Evaluate 5 strict pass/fail conditions for a benchmark query result.

    Returns:
        (passed: bool, failed_at_stage: str, error_message: str)
    """
    # 1. Pipeline completes without unhandled exception / string error
    if isinstance(result, str):
        if result.startswith("Refused:"):
            return False, "guardrail", result
        return False, "synthesis", f"Pipeline returned error string: {result}"

    # 2. Generated SQL passes AST/read-only check
    sql = result.sql
    if not sql:
        return False, "sql_gen", "No SQL query was generated by Stage 2."

    try:
        ast_validate_sql(sql)
    except Exception as ast_err:
        return False, "validation", f"AST validation failed for generated SQL: {ast_err}"

    # 3. Query executes against BigQuery without execution error
    if result.exec_status == "ERROR":
        return False, "execution", f"BigQuery execution failed for SQL: {sql}"

    # 4. Result is either non-empty row set or legitimate zero-row result (not error)
    if result.rows is None and result.exec_status not in ("SUCCESS", "EMPTY"):
        return False, "execution", "Query produced null result rows without valid execution status."

    # 5. Answer synthesis produces non-empty natural-language answer
    answer = result.answer
    if not answer or not answer.strip():
        return False, "synthesis", "Answer synthesis produced an empty answer string."

    return True, "none", ""


def evaluate_expected_check(entry: Dict[str, Any], result: PipelineResult) -> bool:
    """Evaluate optional expected_check assertion if present."""
    check = entry.get("expected_check")
    if not check:
        return True

    check_type = check.get("type")
    val = check.get("value")
    answer = (result.answer or "").lower()

    if check_type == "answer_contains" and val:
        return val.lower() in answer
    elif check_type == "non_empty":
        return bool(result.answer and result.answer.strip())

    return True


def run_benchmark(
    limit: int | None = None,
    fail_under: float | None = None,
    output_path: pathlib.Path | None = None,
) -> Dict[str, Any]:
    """Execute the benchmark suite against the live PWA pipeline."""
    queries = load_benchmark_queries()
    if limit and limit > 0:
        queries = queries[:limit]

    total_queries = len(queries)
    print("\n================================================================================")
    print("  PWA NL->SQL 50-Query Live Pipeline Benchmark Harness")
    print(f"  Queries to run: {total_queries}  | Timestamp: {datetime.datetime.now().isoformat()}")
    print("================================================================================\n")

    results_data: List[Dict[str, Any]] = []
    passed_count = 0
    failed_count = 0
    cat_summary: Dict[str, Dict[str, int]] = {}

    t0_suite = time.perf_counter()

    for idx, entry in enumerate(queries, 1):
        qid = entry.get("id", f"q{idx:02d}")
        category = entry.get("category", "unknown")
        question = entry.get("question", "")

        if category not in cat_summary:
            cat_summary[category] = {"total": 0, "passed": 0, "failed": 0}
        cat_summary[category]["total"] += 1

        t0_q = time.perf_counter()

        try:
            res = run_query_verbose(question, timeout_seconds=120.0)
        except Exception as exc:
            res = f"[EXCEPTION] {exc}"

        latency_ms = round((time.perf_counter() - t0_q) * 1000, 1)

        is_pass, failed_at_stage, error_msg = evaluate_query_conditions(entry, res)
        expected_match = evaluate_expected_check(entry, res) if is_pass and isinstance(res, PipelineResult) else False

        if is_pass:
            passed_count += 1
            cat_summary[category]["passed"] += 1
            status_str = "PASS"
        else:
            failed_count += 1
            cat_summary[category]["failed"] += 1
            status_str = f"FAIL ({failed_at_stage})"

        answer_str = res.answer if isinstance(res, PipelineResult) else str(res)
        sql_str = res.sql if isinstance(res, PipelineResult) else None
        bytes_scanned = res.bytes_scanned if isinstance(res, PipelineResult) else 0

        print(
            f"[{idx:02d}/{total_queries:02d}] {qid:<5} | {category:<15} | {status_str:<18} | "
            f"{latency_ms:>6.0f}ms | '{question[:40]}...'"
        )

        results_data.append(
            {
                "id": qid,
                "category": category,
                "question": question,
                "pass": is_pass,
                "failed_at_stage": failed_at_stage,
                "error_message": error_msg,
                "generated_sql": sql_str,
                "row_count": res.row_count if isinstance(res, PipelineResult) else 0,
                "answer": answer_str,
                "bytes_scanned": bytes_scanned,
                "actual_bytes_processed": getattr(res, "actual_bytes_processed", bytes_scanned)
                if isinstance(res, PipelineResult)
                else 0,
                "slot_ms": getattr(res, "slot_ms", 0) if isinstance(res, PipelineResult) else 0,
                "latency_ms": latency_ms,
                "stage_latencies_ms": {k: round(v * 1000, 1) for k, v in res.stage_latencies.items()}
                if isinstance(res, PipelineResult)
                else {},
                "expected_match": expected_match,
            }
        )

    total_suite_latency_s = round(time.perf_counter() - t0_suite, 2)
    pass_rate = round(100.0 * passed_count / total_queries, 1) if total_queries else 0.0

    total_bytes = sum(r.get("bytes_scanned") or 0 for r in results_data)

    print("\n--------------------------------------------------------------------------------")
    print(" BENCHMARK SUMMARY REPORT")
    print(
        f" Total Queries: {total_queries} | Passed: {passed_count} | Failed: {failed_count} | Pass Rate: {pass_rate}%"
    )
    print(
        f" Total Suite Wall-Clock Latency: {total_suite_latency_s}s | Total Bytes Scanned: {total_bytes / (1024 * 1024):.2f} MB"
    )
    print("--------------------------------------------------------------------------------")
    print(f"{'Category':<20} | {'Total':<8} | {'Passed':<8} | {'Failed':<8} | {'Pass Rate':<10}")
    print("-" * 64)

    for cat, stats in cat_summary.items():
        cat_pass_rate = round(100.0 * stats["passed"] / stats["total"], 1) if stats["total"] else 0.0
        print(f"{cat:<20} | {stats['total']:<8} | {stats['passed']:<8} | {stats['failed']:<8} | {cat_pass_rate:>8.1f}%")

    # Failing Query Breakdown
    failing_items = [r for r in results_data if not r["pass"]]
    if failing_items:
        print("\n--------------------------------------------------------------------------------")
        print(f" FAILING QUERY BREAKDOWN ({len(failing_items)} queries)")
        print("--------------------------------------------------------------------------------")
        for f in failing_items:
            print(f"• ID: {f['id']} ({f['category']}) | Stage: {f['failed_at_stage']}")
            print(f"  Question: '{f['question']}'")
            print(f"  Error: {f['error_message']}")
            if f.get("generated_sql"):
                print(f"  SQL: {f['generated_sql']}")
            print()

    # Write Raw JSON Output
    timestamp = datetime.datetime.now().strftime("%Y%m%d_%H%M%S")
    _RESULTS_DIR.mkdir(parents=True, exist_ok=True)
    out_file = output_path or (_RESULTS_DIR / f"benchmark_run_{timestamp}.json")

    run_payload = {
        "timestamp": timestamp,
        "total_queries": total_queries,
        "passed": passed_count,
        "failed": failed_count,
        "pass_rate_pct": pass_rate,
        "total_suite_latency_seconds": total_suite_latency_s,
        "total_bytes_scanned": total_bytes,
        "category_summary": cat_summary,
        "queries": results_data,
    }

    out_file.write_text(json.dumps(run_payload, indent=2), encoding="utf-8")
    print(f"Full benchmark results saved to: {out_file.resolve()}\n")

    # Enforce --fail-under if specified
    if fail_under is not None and pass_rate < fail_under:
        print(
            f"[FAIL-UNDER CRITERIA TRIPPED] Pass rate {pass_rate}% is below required {fail_under}%. Exiting non-zero."
        )
        sys.exit(1)

    return run_payload


def main() -> None:
    parser = argparse.ArgumentParser(description="Run PWA 50-Query Live Pipeline Benchmark Harness")
    parser.add_argument("--limit", type=int, default=None, help="Limit number of queries to run")
    parser.add_argument("--fail-under", type=float, default=None, help="Fail if pass rate is under PCT")
    parser.add_argument("--output", type=str, default=None, help="Custom output JSON path")

    args = parser.parse_args()
    logging.basicConfig(level=logging.WARNING)

    out_path = pathlib.Path(args.output) if args.output else None
    run_benchmark(limit=args.limit, fail_under=args.fail_under, output_path=out_path)


if __name__ == "__main__":
    main()
